import { test, expect } from '@playwright/test';
import QRCode from 'qrcode';
import jsQR from 'jsqr';
import { PDFDocument } from 'pdf-lib';
import fs from 'node:fs/promises';

test('Авторазмер: максимум, читаемость, PDF, сохранение и ручной режим', async ({ page }) => {
  await page.goto('/');
  await page.locator('#label-width').fill('40');
  await page.locator('#label-height').fill('60');
  await page.locator('#size').fill('28');
  await page.locator('#fit-label').check();
  await expect(page.locator('#size')).toHaveValue('40');
  await expect(page.locator('#size')).toBeDisabled();
  await page.locator('#photo').setInputFiles({name:'fit.png', mimeType:'image/png', buffer:await QRCode.toBuffer('fit-label-test')});
  await expect(page.locator('#download')).toBeEnabled();
  const pixels = await page.locator('#qr').evaluate(canvas => ({ width:canvas.width, height:canvas.height, data:Array.from(canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data) }));
  const decoded = jsQR(new Uint8ClampedArray(pixels.data), pixels.width, pixels.height);
  expect(decoded.data).toBe('fit-label-test');
  const matrix = QRCode.create('fit-label-test', {errorCorrectionLevel:'M'}).modules;
  const moduleDots = Math.floor(40 * 8 / (matrix.size + 8));
  const black = [];
  for (let y=0;y<pixels.height;y++) for(let x=0;x<pixels.width;x++) if(pixels.data[(y*pixels.width+x)*4]===0) black.push([x,y]);
  expect(Math.max(...black.map(p=>p[0])) - Math.min(...black.map(p=>p[0])) + 1).toBe(matrix.size * moduleDots);
  expect((moduleDots+1)*(matrix.size+8)).toBeGreaterThan(40*8);
  await page.screenshot({path:'qa-artifacts/fit-label.png',fullPage:true});
  await page.locator('#label-height').fill('30');
  await expect(page.locator('#size')).toHaveValue('30');
  const pending = page.waitForEvent('download');
  await page.locator('#download').click();
  const pdf = await PDFDocument.load(await fs.readFile(await (await pending).path()));
  expect(pdf.getPage(0).getWidth()*25.4/72).toBeCloseTo(40,4);
  expect(pdf.getPage(0).getHeight()*25.4/72).toBeCloseTo(30,4);
  await page.reload();
  await expect(page.locator('#fit-label')).toBeChecked();
  await expect(page.locator('#size')).toHaveValue('30');
  await page.locator('#fit-label').uncheck();
  await expect(page.locator('#size')).toHaveValue('28');
  await expect(page.locator('#size')).toBeEnabled();
  await page.locator('#fit-label').check();
  await page.locator('#label-height').fill('20');
  await page.reload();
  await expect(page.locator('#fit-label')).toBeChecked();
  await expect(page.locator('#size')).toHaveValue('20');
  await page.locator('#label-height').fill('0');
  await page.locator('#photo').setInputFiles({name:'fit.png', mimeType:'image/png', buffer:await QRCode.toBuffer('fit-label-test')});
  await expect(page.locator('#download')).toBeDisabled();
  await page.locator('#reset-settings').click();
  await expect(page.locator('#fit-label')).not.toBeChecked();
  await expect(page.locator('#size')).toHaveValue('18');
  await expect(page.locator('#download')).toBeEnabled();
});
